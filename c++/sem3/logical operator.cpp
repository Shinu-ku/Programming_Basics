#include <iostream>
using namespace std;
int main()
{
	bool a = true,b = false;
	cout<<"Logical operator"<<endl;

	cout<<"the value of a:"<<a<<". the value of b:"<<b<<endl<<endl;
	
	cout<<"logical and :"<<(a&&b)<<endl;
	cout<<"logical or :"<<(a||b)<<endl;
	cout<<"logical not :"<<(!a)<<endl;
	cout<<"logical not :"<<(!b)<<endl;

	return 0;
}
